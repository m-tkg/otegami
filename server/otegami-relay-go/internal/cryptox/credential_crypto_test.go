// --- Cross-implementation compatibility fixtures ---
//
// Generated by a standalone Swift program using swift-crypto 3.15.1 (the
// exact version pinned in server/otegami-relay/Package.resolved) calling
// AES.GCM.seal(_:using:).combined — the identical code path
// CredentialCrypto.encrypt(_:) uses. These are NOT round-tripped through
// this Go implementation; they verify this Go implementation can decrypt
// bytes a real Swift relay actually produced and would have persisted to
// SQLite, which is the whole point of Task #180's compatibility
// requirement: an existing production database's `watch.encryptedSecret`
// column must decrypt under this new binary with zero migration.
func TestDecryptsSwiftEncryptedFixtureASCII(t *testing.T) {
	keyB64 := "MDEyMzQ1Njc4OWFiY2RlZjAxMjM0NTY3ODlhYmNkZWY="
	combinedB64 := "VP9OQ6surTn0txwmV5TAa45whEc/jp1phpcN4IcpH3x8sOhNQjPInzRzFpb9iuw="
	wantPlaintext := "s3cr3t-app-password"

	c, err := NewFromBase64Key(keyB64)
	if err != nil {
		t.Fatal(err)
	}
	combined, err := base64.StdEncoding.DecodeString(combinedB64)
	if err != nil {
		t.Fatal(err)
	}
	got, err := c.Decrypt(combined)
	if err != nil {
		t.Fatalf("decrypt failed: %v", err)
	}
	if got != wantPlaintext {
		t.Fatalf("got %q, want %q", got, wantPlaintext)
	}
}

