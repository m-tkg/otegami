func TestNonceIsFresh(t *testing.T) {
	key := make([]byte, 32)
	c, _ := New(key)
	first, _ := c.Encrypt("same-password")
	second, _ := c.Encrypt("same-password")
	if base64.StdEncoding.EncodeToString(first) == base64.StdEncoding.EncodeToString(second) {
		t.Fatal("expected different ciphertexts for repeated encryption (nonce reuse)")
	}
}

func TestWrongKeyFails(t *testing.T) {
	key1 := make([]byte, 32)
	key2 := make([]byte, 32)
	key2[0] = 1
	c1, _ := New(key1)
	c2, _ := New(key2)
	ciphertext, _ := c1.Encrypt("s3cr3t")
	if _, err := c2.Decrypt(ciphertext); err == nil {
		t.Fatal("expected decrypt with wrong key to fail")
	}
}

func TestTamperedCiphertextFails(t *testing.T) {
	key := make([]byte, 32)
	c, _ := New(key)
	ciphertext, _ := c.Encrypt("s3cr3t")
	ciphertext[0] ^= 0xFF
	if _, err := c.Decrypt(ciphertext); err == nil {
		t.Fatal("expected decrypt of tampered ciphertext to fail")
	}
}

