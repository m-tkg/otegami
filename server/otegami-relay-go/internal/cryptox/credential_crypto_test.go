func TestRoundTrip(t *testing.T) {
	key := make([]byte, 32)
	c, err := New(key)
	if err != nil {
		t.Fatal(err)
	}
	ciphertext, err := c.Encrypt("s3cr3t-app-password")
	if err != nil {
		t.Fatal(err)
	}
	plaintext, err := c.Decrypt(ciphertext)
	if err != nil {
		t.Fatal(err)
	}
	if plaintext != "s3cr3t-app-password" {
		t.Fatalf("got %q", plaintext)
	}
}

